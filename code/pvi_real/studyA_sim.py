"""PVI-REAL Study A (computational dry-run of the proposed human RCT).

Mirrors the PVI-REAL protocol with virtual sources generated by the
paper's own model (code/pvi_experiments.py conventions): panels of
sources report on SHARED query items; each source also has its own
labelled support set. Conditions vary the panel's convention mix:

  low       all sources identity (no heterogeneity) -- negative control
  fixed     identity / fixed inversion (scalar-representable)
  context   context-dependent conventions (the paper's regime)
  boundary  context-dependent with rho in [0.5, 0.65] (near-silent)
  emergent  group-shared convention with per-source drift (imperfect
            adoption of a group shorthand)

Methods (identical support for all): MajorityVote, SignedScalar,
LogOddsScalar, ContextMatchFreq, PerContextTM (unrestricted per-cell
transition matrices, the strong classical relative), PVI (grid Bayes,
candidates 0..7), PVI with shuffled source identities, PVI with
shuffled query contexts, PVI with a placebo context bit, Oracle.

Primary metric: held-out log loss of each method's native predictive
probability; secondary: accuracy, Brier. Support sweep
K in {0,2,5,10,20,40} (nested support sets), 20+ episodes per
condition. Outputs: results/pvi_real/studyA_episodes.csv,
studyA_summary.json, studyA_summary.md.
"""
import json
import os
import sys

import numpy as np

sys.path.insert(0, os.path.join(os.path.dirname(__file__), '..'))
from pvi_experiments import bayes_post, RHO_GRID, R_GRID  # noqa: E402

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, '..', '..', 'results', 'pvi_real')
os.makedirs(OUT, exist_ok=True)

CANDS = list(range(8))
PARITY = {  # convention c acts as signal XOR parity_c(a1, a2)
    0: lambda a1, a2: np.zeros_like(a1),
    1: lambda a1, a2: np.ones_like(a1),
    2: lambda a1, a2: a1,
    3: lambda a1, a2: a2,
    4: lambda a1, a2: a1 & a2,
    5: lambda a1, a2: a1 | a2,
    6: lambda a1, a2: a1 ^ a2,
    7: lambda a1, a2: 1 - (a1 & a2),
}
CTX_DEPENDENT = {2, 3, 4, 5, 6, 7}
KS = [0, 2, 5, 10, 20, 40]
KMAX = 40
Q = 40
N_SRC = 6


def parity_matrix(cands, a1, a2):
    return np.stack([PARITY[c](a1, a2) for c in cands], axis=1)  # (n, nc)


def gen_source_data(rng, c, rho, r, sup_items, qry_items):
    """sup_items/qry_items: (Z, a1, a2) arrays; returns messages."""
    def emit(Z, a1, a2):
        R = np.where(rng.random(len(Z)) < r, Z, 1 - Z)
        conv = R ^ PARITY[c](a1, a2)
        use = rng.random(len(Z)) < rho
        return np.where(use, conv, R).astype(np.int64)
    return emit(*sup_items), emit(*qry_items)


def draw_items(rng, n):
    return (rng.integers(0, 2, n), rng.integers(0, 2, n),
            rng.integers(0, 2, n))


def sample_panel(rng, condition):
    srcs = []
    if condition == 'emergent':
        cg = int(rng.integers(2, 8))
    for _ in range(N_SRC):
        if condition == 'low':
            c = 0
            rho = rng.uniform(0.7, 1.0)
        elif condition == 'fixed':
            c = int(rng.integers(0, 2))
            rho = rng.uniform(0.7, 1.0)
        elif condition == 'context':
            c = int(rng.integers(0, 8))
            rho = rng.uniform(0.6, 1.0)
        elif condition == 'boundary':
            c = int(rng.choice([2, 3, 4, 6]))
            rho = float(rng.choice([0.5, 0.55, 0.6, 0.65]))
        elif condition == 'emergent':
            c = cg if rng.random() < 0.75 else int(rng.integers(0, 8))
            rho = rng.uniform(0.55, 0.9)
        else:
            raise ValueError(condition)
        r = rng.uniform(0.7, 0.95)
        srcs.append((int(c), float(rho), float(r)))
    if condition == 'context':
        # guarantee at least 3 context-dependent sources per panel
        n_ctx = sum(s[0] in CTX_DEPENDENT for s in srcs)
        j = 0
        while n_ctx < 3:
            if srcs[j][0] not in CTX_DEPENDENT:
                srcs[j] = (int(rng.integers(2, 8)), srcs[j][1], srcs[j][2])
                n_ctx += 1
            j += 1
    return srcs


def true_cell_acc(c, rho, r, a1, a2):
    p = int(PARITY[c](np.array([a1]), np.array([a2]))[0])
    return rho * ((1 - r) if p else r) + (1 - rho) * r


def heterogeneity(srcs):
    """Mean over sources of the across-context spread in P(m = z)."""
    vals = []
    for c, rho, r in srcs:
        accs = [true_cell_acc(c, rho, r, a1, a2)
                for a1 in (0, 1) for a2 in (0, 1)]
        vals.append(max(accs) - min(accs))
    return float(np.mean(vals))


# ---------------- method scorers (return per-query log-odds or probs) ----
def sigmoid(x):
    return 1.0 / (1.0 + np.exp(-np.clip(x, -30, 30)))


def pvi_log_odds(post, m, a1, a2, cands=CANDS):
    """Vectorised posterior-predictive log-odds (matches bayes_log_odds)."""
    P = parity_matrix(cands, a1, a2)                    # (nq, nc)
    A = m[:, None] ^ P                                   # decoded reading
    B = m.astype(float)                                  # (nq,)
    rho_b = RHO_GRID[None, :, None]
    r_b = R_GRID[None, None, :]
    X1 = rho_b[None] * A[:, :, None, None] + (1 - rho_b[None]) * B[:, None, None, None]
    p1 = (1 - r_b[None]) + X1 * (2 * r_b[None] - 1)
    X0 = rho_b[None] * (1 - A)[:, :, None, None] + (1 - rho_b[None]) * (1 - B)[:, None, None, None]
    p0 = (1 - r_b[None]) + X0 * (2 * r_b[None] - 1)
    p1_bar = np.einsum('cxy,qcxy->q', post, p1)
    p0_bar = np.einsum('cxy,qcxy->q', post, p0)
    return np.log(np.clip(p1_bar, 1e-12, None)) - np.log(np.clip(p0_bar, 1e-12, None))


def oracle_lo(m, a1, a2, c, rho, r):
    A = (m ^ PARITY[c](a1, a2)).astype(float)
    B = m.astype(float)
    X1 = rho * A + (1 - rho) * B
    p1 = (1 - r) + X1 * (2 * r - 1)
    X0 = rho * (1 - A) + (1 - rho) * (1 - B)
    p0 = (1 - r) + X0 * (2 * r - 1)
    return np.log(np.clip(p1, 1e-12, None)) - np.log(np.clip(p0, 1e-12, None))


def run_episode(rng, condition):
    srcs = sample_panel(rng, condition)
    qry_items = draw_items(rng, Q)
    Zq = qry_items[0]
    sup, qry = [], []
    for (c, rho, r) in srcs:
        sup_items = draw_items(rng, KMAX)
        s_msg, q_msg = gen_source_data(rng, c, rho, r, sup_items, qry_items)
        sup.append((s_msg, *sup_items))
        qry.append(q_msg)
    Mq = np.stack(qry)                                   # (N, Q)
    het = heterogeneity(srcs)
    rows = []
    for K in KS:
        # --- per-source fits on the first K support items ---
        posts, posts_pl = [], []
        w_signed, w_logodds = [], []
        cons_cell, tm_counts = [], []
        a2_pl = [rng.integers(0, 2, K) if K else np.array([], dtype=int)
                 for _ in srcs]
        for j, (c, rho, r) in enumerate(srcs):
            # sup tuples are (msg, Z, a1, a2) -- mind the order.
            sm, sz, s1, s2 = (sup[j][0][:K], sup[j][1][:K],
                              sup[j][2][:K], sup[j][3][:K])
            if K == 0:
                post = np.full((len(CANDS), len(RHO_GRID), len(R_GRID)),
                               1.0 / (len(CANDS) * len(RHO_GRID) * len(R_GRID)))
                posts.append(post)
                posts_pl.append(post)
                w_signed.append(0.0)
                w_logodds.append(0.0)
                cons_cell.append({})
                tm_counts.append(None)
                continue
            posts.append(bayes_post(sm, s1, s2, sz, CANDS))
            posts_pl.append(bayes_post(sm, s1, a2_pl[j], sz, CANDS))
            hits = float((sm == sz).mean())
            w_signed.append(2 * hits - 1)
            cons_s = (sm == sz).sum() + 1
            cons_s = cons_s / (K + 2)
            w_logodds.append(np.log(cons_s / (1 - cons_s)))
            cc = {}
            for a1 in (0, 1):
                for a2 in (0, 1):
                    sel = (s1 == a1) & (s2 == a2)
                    if sel.sum() >= 3:
                        cc[(a1, a2)] = 2 * float((sm[sel] == sz[sel]).mean()) - 1
            cons_cell.append(cc)
            tm_counts.append((sm, s1, s2, sz))
        # --- scoring ---
        qa1, qa2 = qry_items[1], qry_items[2]
        p = {}
        p['Majority'] = np.clip(Mq.mean(axis=0), 0.02, 0.98)
        lo = np.zeros(Q)
        for j in range(N_SRC):
            lo += w_signed[j] * (2 * Mq[j] - 1)
        p['SignedScalar'] = sigmoid(lo)
        lo = np.zeros(Q)
        for j in range(N_SRC):
            lo += w_logodds[j] * (2 * Mq[j] - 1)
        p['LogOddsScalar'] = sigmoid(lo)
        lo = np.zeros(Q)
        for j in range(N_SRC):
            for i in range(Q):
                w = cons_cell[j].get((qa1[i], qa2[i]), w_signed[j])
                lo[i] += w * (2 * Mq[j, i] - 1)
        p['ContextMatchFreq'] = sigmoid(lo)
        lo = np.zeros(Q)
        for j in range(N_SRC):
            if tm_counts[j] is None:
                continue
            sm, s1, s2, sz = tm_counts[j]
            for a1 in (0, 1):
                for a2 in (0, 1):
                    sel_q = (qa1 == a1) & (qa2 == a2)
                    if not sel_q.any():
                        continue
                    sel_s = (s1 == a1) & (s2 == a2)
                    if sel_s.sum() < 4:
                        sel_s = np.ones_like(sm, dtype=bool)
                    z1 = sz[sel_s] == 1
                    p11 = (sm[sel_s][z1].sum() + 1) / (z1.sum() + 2)
                    z0 = ~z1
                    p10 = (sm[sel_s][z0].sum() + 1) / (z0.sum() + 2)
                    m_q = Mq[j, sel_q]
                    lo[sel_q] += np.where(
                        m_q == 1, np.log(p11) - np.log(p10),
                        np.log(1 - p11) - np.log(1 - p10))
        p['PerContextTM'] = sigmoid(lo)
        lo = np.zeros(Q)
        for j in range(N_SRC):
            lo += pvi_log_odds(posts[j], Mq[j], qa1, qa2)
        p['PVI'] = sigmoid(lo)
        lo = np.zeros(Q)
        for j in range(N_SRC):
            lo += pvi_log_odds(posts[(j + 1) % N_SRC], Mq[j], qa1, qa2)
        p['PVI_srcshuffle'] = sigmoid(lo)
        perm = rng.permutation(Q)
        lo = np.zeros(Q)
        for j in range(N_SRC):
            lo += pvi_log_odds(posts[j], Mq[j], qa1[perm], qa2[perm])
        p['PVI_ctxshuffle'] = sigmoid(lo)
        qa2_pl = rng.integers(0, 2, Q)
        lo = np.zeros(Q)
        for j in range(N_SRC):
            lo += pvi_log_odds(posts_pl[j], Mq[j], qa1, qa2_pl)
        p['PVI_placebo'] = sigmoid(lo)
        lo = np.zeros(Q)
        for j, (c, rho, r) in enumerate(srcs):
            lo += oracle_lo(Mq[j], qa1, qa2, c, rho, r)
        p['Oracle'] = sigmoid(lo)
        # PVI convention recovery at this K
        rec_mass, rec_map = [], []
        for j, (c, rho, r) in enumerate(srcs):
            pm = posts[j].sum(axis=(1, 2))
            rec_mass.append(float(pm[c]))
            rec_map.append(int(np.argmax(pm) == c))
        for meth, prob in p.items():
            prob = np.clip(prob, 1e-9, 1 - 1e-9)
            ll = -np.mean(Zq * np.log(prob) + (1 - Zq) * np.log(1 - prob))
            acc = np.mean((prob > 0.5).astype(int) == Zq)
            brier = np.mean((prob - Zq) ** 2)
            rows.append({'condition': condition, 'K': K, 'method': meth,
                         'logloss': float(ll), 'acc': float(acc),
                         'brier': float(brier), 'het': het,
                         'rec_mass': float(np.mean(rec_mass)),
                         'rec_map': float(np.mean(rec_map))})
    return rows


def main():
    n_ep = int(sys.argv[1]) if len(sys.argv) > 1 else 40
    rng = np.random.default_rng(20261021)
    all_rows = []
    for cond in ['low', 'fixed', 'context', 'boundary', 'emergent']:
        for ep in range(n_ep):
            rows = run_episode(rng, cond)
            for row in rows:
                row['episode'] = ep
            all_rows.extend(rows)
            print(f'{cond} ep {ep + 1}/{n_ep}', flush=True)
    import csv
    with open(os.path.join(OUT, 'studyA_episodes.csv'), 'w', newline='') as f:
        wtr = csv.DictWriter(f, fieldnames=list(all_rows[0].keys()))
        wtr.writeheader()
        wtr.writerows(all_rows)
    # ---------- summaries ----------
    import collections
    summ = {}
    for cond in ['low', 'fixed', 'context', 'boundary', 'emergent']:
        summ[cond] = {}
        for K in KS:
            summ[cond][K] = {}
            for meth in ['Majority', 'SignedScalar', 'LogOddsScalar',
                         'ContextMatchFreq', 'PerContextTM', 'PVI',
                         'PVI_srcshuffle', 'PVI_ctxshuffle', 'PVI_placebo',
                         'Oracle']:
                vals = [r for r in all_rows if r['condition'] == cond
                        and r['K'] == K and r['method'] == meth]
                summ[cond][K][meth] = {
                    'logloss': float(np.mean([v['logloss'] for v in vals])),
                    'logloss_se': float(np.std([v['logloss'] for v in vals]) / np.sqrt(len(vals))),
                    'acc': float(np.mean([v['acc'] for v in vals])),
                    'brier': float(np.mean([v['brier'] for v in vals]))}
    # paired advantage of PVI over LogOddsScalar at K=20, by episode
    adv = {}
    for cond in summ:
        diffs = []
        for ep in range(n_ep):
            a = [r for r in all_rows if r['condition'] == cond and r['episode'] == ep and r['K'] == 20 and r['method'] == 'LogOddsScalar']
            b = [r for r in all_rows if r['condition'] == cond and r['episode'] == ep and r['K'] == 20 and r['method'] == 'PVI']
            if a and b:
                diffs.append((a[0]['logloss'] - b[0]['logloss'],
                              a[0]['acc'] - b[0]['acc'], a[0]['het']))
        adv[cond] = diffs
    # heterogeneity interaction across all conditions
    xs = np.array([d[2] for c in adv.values() for d in c])
    ys = np.array([d[0] for c in adv.values() for d in c])
    rngb = np.random.default_rng(7)
    slopes = []
    for _ in range(2000):
        idx = rngb.integers(0, len(xs), len(xs))
        if np.std(xs[idx]) > 1e-9:
            slopes.append(np.polyfit(xs[idx], ys[idx], 1)[0])
    interaction = {'slope': float(np.polyfit(xs, ys, 1)[0]),
                   'slope_ci': [float(np.percentile(slopes, 2.5)),
                                float(np.percentile(slopes, 97.5))],
                   'spearman': float(np.corrcoef(
                       np.argsort(np.argsort(xs)),
                       np.argsort(np.argsort(ys)))[0, 1])}
    # sample efficiency: smallest K where PVI logloss <= LogOddsScalar@40
    eff = {}
    for cond in summ:
        target = summ[cond][40]['LogOddsScalar']['logloss']
        kk = next((K for K in KS if summ[cond][K]['PVI']['logloss'] <= target), None)
        eff[cond] = {'target_logloss': target, 'K_reached': kk,
                     'label_ratio': (kk / 40) if kk is not None else None}
    # power analysis from context-condition paired diffs (episode level)
    diffs_ll = np.array([d[0] for d in adv['context']])
    diffs_acc = np.array([d[1] for d in adv['context']])
    def power_curve(diffs):
        out = {}
        for n in [5, 10, 15, 20, 30, 40, 60, 80]:
            hits = 0
            for _ in range(2000):
                s = rngb.choice(diffs, size=n, replace=True)
                z = s.mean() / (s.std(ddof=1) / np.sqrt(n) + 1e-12)
                hits += z > 1.96
            out[n] = hits / 2000
        return out
    power = {'logloss': power_curve(diffs_ll), 'acc': power_curve(diffs_acc),
             'mean_diff_logloss': float(diffs_ll.mean()),
             'mean_diff_acc': float(diffs_acc.mean())}
    result = {'n_episodes_per_condition': n_ep, 'summary': summ,
              'interaction': interaction, 'sample_efficiency': eff,
              'power_context_K20': power,
              'advantage_K20': {c: {'logloss': float(np.mean([d[0] for d in adv[c]])),
                                    'acc': float(np.mean([d[1] for d in adv[c]]))}
                                for c in adv}}
    with open(os.path.join(OUT, 'studyA_summary.json'), 'w') as f:
        json.dump(result, f, indent=2)
    print(json.dumps({'interaction': interaction, 'sample_efficiency': eff,
                      'power': power, 'advantage_K20': result['advantage_K20']},
                     indent=2))


if __name__ == '__main__':
    main()
